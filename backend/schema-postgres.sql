CREATE TABLE IF NOT EXISTS users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(100) NOT NULL, email VARCHAR(190) NOT NULL, phone VARCHAR(30) NOT NULL DEFAULT '', password VARCHAR(100) NOT NULL,
 google_sub VARCHAR(255) UNIQUE, google_email VARCHAR(190), password_login_enabled SMALLINT NOT NULL DEFAULT 1 CHECK(password_login_enabled IN (0,1)), phone_verified SMALLINT NOT NULL DEFAULT 0 CHECK(phone_verified IN (0,1)), phone_verification_method VARCHAR(20), phone_verified_at TIMESTAMPTZ,
 role VARCHAR(20) NOT NULL DEFAULT 'customer' CHECK(role IN ('admin','sales','customer')), active SMALLINT NOT NULL DEFAULT 1 CHECK(active IN (0,1)), session_version INTEGER NOT NULL DEFAULT 1, created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS unique_users_email_ci ON users(LOWER(email));
CREATE INDEX IF NOT EXISTS idx_users_role_active ON users(role,active);

CREATE TABLE IF NOT EXISTS categories (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(100) NOT NULL, description TEXT NOT NULL, image VARCHAR(255) NOT NULL DEFAULT '', active SMALLINT NOT NULL DEFAULT 1 CHECK(active IN (0,1)), created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS unique_categories_name_ci ON categories(LOWER(name));

CREATE TABLE IF NOT EXISTS products (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(150) NOT NULL, description TEXT NOT NULL, price NUMERIC(10,2) NOT NULL, sale_price NUMERIC(10,2), unit VARCHAR(40) NOT NULL DEFAULT 'packet', stock INTEGER NOT NULL DEFAULT 0,
 category_id BIGINT REFERENCES categories(id) ON DELETE SET NULL, images JSONB NOT NULL, active SMALLINT NOT NULL DEFAULT 1 CHECK(active IN (0,1)), featured SMALLINT NOT NULL DEFAULT 0 CHECK(featured IN (0,1)), created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CHECK(stock>=0), CHECK(price>=0), CHECK(sale_price IS NULL OR (sale_price>=0 AND sale_price<=price))
);
CREATE INDEX IF NOT EXISTS idx_products_catalog ON products(active,category_id);
CREATE INDEX IF NOT EXISTS idx_products_featured ON products(active,featured);

CREATE TABLE IF NOT EXISTS settings (id INTEGER PRIMARY KEY, content JSONB NOT NULL, updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE IF NOT EXISTS carts (user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE, items JSONB NOT NULL, updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP);

CREATE TABLE IF NOT EXISTS orders (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id), address JSONB NOT NULL, subtotal NUMERIC(12,2) NOT NULL, delivery_charge NUMERIC(10,2) NOT NULL DEFAULT 0, total NUMERIC(12,2) NOT NULL,
 status VARCHAR(30) NOT NULL DEFAULT 'Pending', payment_method VARCHAR(20) NOT NULL DEFAULT 'cod', payment_status VARCHAR(30) NOT NULL DEFAULT 'cod', gateway_order_id VARCHAR(100) UNIQUE, gateway_payment_id VARCHAR(100) UNIQUE,
 idempotency_key VARCHAR(100), checkout_hash CHAR(64), stock_restored SMALLINT NOT NULL DEFAULT 0 CHECK(stock_restored IN (0,1)), tracking VARCHAR(150) NOT NULL DEFAULT '', delivery_notes TEXT NOT NULL,
 latitude NUMERIC(10,7), longitude NUMERIC(10,7), driver_lat NUMERIC(10,7), driver_lng NUMERIC(10,7), driver_source VARCHAR(20), driver_updated_at TIMESTAMPTZ,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT unique_checkout UNIQUE(user_id,idempotency_key)
);
CREATE INDEX IF NOT EXISTS idx_orders_owner ON orders(user_id,id);
CREATE INDEX IF NOT EXISTS idx_orders_status ON orders(status,created_at);
CREATE INDEX IF NOT EXISTS idx_orders_created ON orders(created_at);

CREATE TABLE IF NOT EXISTS order_items (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, order_id BIGINT NOT NULL REFERENCES orders(id), product_id BIGINT NOT NULL REFERENCES products(id), name VARCHAR(150) NOT NULL, quantity INTEGER NOT NULL CHECK(quantity>0), price NUMERIC(10,2) NOT NULL, unit VARCHAR(40) NOT NULL, image VARCHAR(255) NOT NULL DEFAULT '',
 CONSTRAINT unique_order_product UNIQUE(order_id,product_id)
);
CREATE TABLE IF NOT EXISTS order_activity (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, order_id BIGINT NOT NULL REFERENCES orders(id), actor BIGINT REFERENCES users(id), status VARCHAR(30) NOT NULL, detail VARCHAR(500) NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_order_activity ON order_activity(order_id,id);

CREATE TABLE IF NOT EXISTS leads (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(100) NOT NULL, email VARCHAR(190) NOT NULL, phone VARCHAR(30) NOT NULL, product VARCHAR(150) NOT NULL, quantity INTEGER NOT NULL CHECK(quantity>=0), message TEXT NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'New' CHECK(status IN ('New','Contacted','Converted','Lost')), followup DATE, user_id BIGINT REFERENCES users(id), created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_leads_status ON leads(status,created_at);
CREATE INDEX IF NOT EXISTS idx_leads_followup ON leads(followup,status);
CREATE INDEX IF NOT EXISTS idx_leads_customer ON leads(user_id,id);
CREATE TABLE IF NOT EXISTS lead_notes (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, lead_id BIGINT NOT NULL REFERENCES leads(id), actor BIGINT NOT NULL REFERENCES users(id), note TEXT NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
