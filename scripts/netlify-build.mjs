import { access, mkdir, rename, writeFile } from "node:fs/promises";
import { isIP } from "node:net";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { spawnSync } from "node:child_process";

const projectRoot = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
);
const originError =
  "BACKEND_ORIGIN must be the separate API server’s public HTTPS origin, without credentials, a path, query or fragment.";

/** Validate configuration before constructing any routing rule or running Vite. */
export function validateBackendOrigin(value, frontendOrigins = []) {
  if (typeof value !== "string" || value.length === 0) {
    throw new Error(
      "BACKEND_ORIGIN is required. Set it in Netlify’s build environment; no API target is assumed.",
    );
  }
  // Reject whitespace, URL normalization tricks and redirect-file injection.
  // The backend host must use a public, fully qualified DNS name, not an IP.
  if (!/^https:\/\/[a-z0-9.-]+(?::[1-9][0-9]{0,4})?\/?$/i.test(value)) {
    throw new Error(originError);
  }
  let url;
  try {
    url = new URL(value);
  } catch {
    throw new Error(originError);
  }
  const hostname = url.hostname.toLowerCase();
  const labels = hostname.split(".");
  if (
    url.protocol !== "https:" ||
    url.username ||
    url.password ||
    url.search ||
    url.hash ||
    url.pathname !== "/" ||
    hostname.length > 253 ||
    labels.length < 2 ||
    isIP(hostname) ||
    labels.some(
      (label) => !/^[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?$/.test(label),
    ) ||
    !/^[a-z][a-z0-9-]*$/.test(labels.at(-1)) ||
    /(?:^|\.)(?:localhost|local|localdomain|internal|lan|home|test|invalid|example)$/.test(
      hostname,
    )
  ) {
    throw new Error(originError);
  }
  for (const frontend of frontendOrigins.filter(Boolean)) {
    let publicOrigin;
    try {
      publicOrigin = new URL(frontend).origin;
    } catch {
      continue;
    }
    if (url.origin === publicOrigin) {
      throw new Error(
        "BACKEND_ORIGIN cannot be the Netlify storefront origin: that would create a proxy loop.",
      );
    }
  }
  return url.origin;
}

export function createRedirects(value, frontendOrigins = []) {
  const origin = validateBackendOrigin(value, frontendOrigins);
  return [
    "# Generated by scripts/netlify-build.mjs. Do not commit a deployment-specific target.",
    "# Preserve the browser origin for host-only session/CSRF cookies and uploads.",
    `/api ${origin}/api 200!`,
    `/api/* ${origin}/api/:splat 200!`,
    `/uploads ${origin}/uploads 200!`,
    `/uploads/* ${origin}/uploads/:splat 200!`,
    `/socket.io ${origin}/socket.io/ 200!`,
    `/socket.io/* ${origin}/socket.io/:splat 200!`,
    "# Existing static assets take precedence; all client-side routes use React.",
    "/* /index.html 200",
    "",
  ].join("\n");
}

export function netlifyClientEnvironment(environment) {
  // This public build flag is the only frontend change. Never forward backend
  // credentials through VITE_* variables. BACKEND_ORIGIN is used in routes only.
  return { ...environment, VITE_DEPLOY_TARGET: "netlify" };
}

export async function writeRedirects(
  publishDirectory,
  value,
  frontendOrigins = [],
) {
  const content = createRedirects(value, frontendOrigins);
  await mkdir(publishDirectory, { recursive: true });
  const target = path.join(publishDirectory, "_redirects");
  const temporary = path.join(publishDirectory, "_redirects.tmp");
  await writeFile(temporary, content, { encoding: "utf8", mode: 0o644 });
  await rename(temporary, target);
  return target;
}

export async function buildNetlify(environment = process.env) {
  const frontendOrigins = [
    environment.URL,
    environment.DEPLOY_URL,
    environment.DEPLOY_PRIME_URL,
  ];
  const origin = validateBackendOrigin(
    environment.BACKEND_ORIGIN,
    frontendOrigins,
  );
  const frontend = path.join(projectRoot, "frontend");
  const vite = path.join(frontend, "node_modules", "vite", "bin", "vite.js");
  try {
    await access(vite);
  } catch {
    throw new Error(
      "Frontend dependencies are missing. Run npm --prefix frontend ci before this local Netlify build.",
    );
  }
  const result = spawnSync(process.execPath, [vite, "build"], {
    cwd: frontend,
    env: netlifyClientEnvironment(environment),
    stdio: "inherit",
  });
  if (result.error) throw result.error;
  if (result.status !== 0) {
    throw new Error(
      `Frontend build failed (exit ${result.status ?? "unknown"}); no Netlify routes were generated.`,
    );
  }
  await writeRedirects(path.join(frontend, "dist"), origin, frontendOrigins);
  console.log(
    "Netlify frontend built with validated same-origin API/media proxies and HTTP polling.",
  );
}

if (
  process.argv[1] &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  buildNetlify().catch((error) => {
    console.error(error.message);
    process.exitCode = 1;
  });
}
